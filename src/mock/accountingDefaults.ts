/**
 * Ensures any dynamic CashBankAccount (including newly added banks) has a corresponding
 * leaf COA sub-account under 1110 Cash in Hand or 1120 Cash at Bank.
 */
export function ensureCOAForCashBankAccounts(
  coaAccounts: COAAccount[],
  cashBankAccounts: CashBankAccount[]
): COAAccount[] {
  const next = [...coaAccounts];
  cashBankAccounts.forEach((cb) => {
    const exists = next.some((c) => c.linkedCashBankAccountId === cb.id);
    if (!exists) {
      const isCash = cb.type === 'Cash';
      const parentId = isCash ? COA_IDS.CASH_IN_HAND_GROUP : COA_IDS.CASH_AT_BANK_GROUP;
      const prefix = isCash ? '111' : '112';
      const existingSiblingCodes = next
        .filter((c) => c.parentId === parentId)
        .map((c) => parseInt(c.code, 10))
        .filter((n) => !Number.isNaN(n));
      const nextCode =
        existingSiblingCodes.length > 0
          ? String(Math.max(...existingSiblingCodes) + 1)
          : `${prefix}9`;

      next.push({
        id: `coa-cb-${cb.id}`,
        code: nextCode,
        name: cb.name,
        category: 'Asset',
        classification: 'Current Asset',
        parentId,
        level: 4,
        isGroup: false,
        isSystem: true,
        normalBalance: 'Debit',
        isActive: cb.status === 'Active',
        linkedCashBankAccountId: cb.id,
        description: `Linked ${cb.type} Book account (${cb.accountNumber || cb.id})`,
        createdBy: 'System',
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      });
    }
  });
  return next;
}
