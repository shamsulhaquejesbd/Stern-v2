export function buildMonthlyPeriodsForYear(
  fyId: string,
  startDate: string,
  endDate: string
): AccountingPeriod[] {
  const start = new Date(`${startDate}T00:00:00`);
  const end = new Date(`${endDate}T00:00:00`);
  if (Number.isNaN(start.getTime()) || Number.isNaN(end.getTime()) || start > end) {
    return [];
  }

  const periods: AccountingPeriod[] = [];
  let cursor = new Date(start.getFullYear(), start.getMonth(), 1);
  let idx = 1;

  while (cursor <= end && idx <= 24) {
    const year = cursor.getFullYear();
    const month = cursor.getMonth();
    const firstDay = new Date(year, month, 1);
    const lastDay = new Date(year, month + 1, 0);

    const periodStart = firstDay < start ? start : firstDay;
    const periodEnd = lastDay > end ? end : lastDay;

    const monthName = periodStart.toLocaleString('en-US', { month: 'short' });
    const fmt = (d: Date) =>
      `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;

    periods.push({
      id: `${fyId}-p${String(idx).padStart(2, '0')}`,
      financialYearId: fyId,
      name: `${monthName} ${year}`,
      periodNumber: idx,
      startDate: fmt(periodStart),
      endDate: fmt(periodEnd),
      status: 'Open',
    });

    idx += 1;
    cursor = new Date(year, month + 1, 1);
  }

  return periods;
}

export const DEFAULT_FINANCIAL_YEARS: FinancialYear[] = (() => {
  const yr = new Date().getFullYear();
  const fyId = `fy-${yr}`;
  const start = `${yr}-01-01`;
  const end = `${yr}-12-31`;
  return [
    {
      id: fyId,
      name: `FY ${yr}`,
      startDate: start,
      endDate: end,
      isActive: true,
      status: 'Open',
      periods: buildMonthlyPeriodsForYear(fyId, start, end),
    },
  ];
})();

